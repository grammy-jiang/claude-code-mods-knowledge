from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "evals/fixtures/cli304-official-toolcheck-review/toolcheck-delta.ts"
MANIFEST = FIXTURE.parent / "source-hashes.json"
CORE302 = "8afa71883ecfa52901eb7a04cf31fef700d8ba565eaad244f4884cc620f8d56e"
CORE304 = "6694767741c445872577d96a55fb08816d0f4b5783bc49e1eacd55f27b383308"
NATIVE304 = "c487117526509ab6d2ee6013e14f181faf68d6d6afe6bb0d4b2b4a9feca5ecb3"
ASSET304 = "17cc5d933babad064bed65b3a4fbafab29556fbbfc12aa7888ae1f6c320e08c5"
SOURCE_SHA = "d103f782bea523878d6978354498c25111c1384df60a9d37cb9be83e32c80884"


class Review304Blocked(ValueError):
    """A current 2.1.304 type claim must not be based on a guessed source."""


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _tsc(work: Path, tsc: str, node: str) -> tuple[int, list[str]]:
    proc = subprocess.run(  # noqa: S603 - local official TS compiler, noEmit
        [tsc, "--project", str(work / "tsconfig.json"), "--pretty", "false"],
        cwd=work,
        text=True,
        capture_output=True,
        timeout=25,
        check=False,
        env={"PATH": str(Path(node).parent) + ":/usr/bin:/bin", "LANG": "C.UTF-8"},
    )
    if proc.stderr or proc.returncode not in (0, 2) or len(proc.stdout) > 15_000:
        raise Review304Blocked("Unbounded or unexpected TypeScript output")
    codes = re.findall(r"error (TS\d+):", proc.stdout)
    if proc.returncode == 0 and codes:
        raise Review304Blocked("Reported type errors with successful compiler exit")
    return proc.returncode, codes


def audit(
    older_core: Path,
    current_core: Path,
    native_binary: Path,
    official_asset: Path,
) -> dict:
    files = {
        "old": (older_core, CORE302),
        "new": (current_core, CORE304),
        "binary": (native_binary, NATIVE304),
        "asset": (official_asset, ASSET304),
        "probe": (FIXTURE, SOURCE_SHA),
    }
    if any(
        not path.is_file() or path.is_symlink() or sha(path) != digest
        for path, digest in files.values()
    ):
        raise Review304Blocked("Official native binary/core type or probe hash mismatch")
    manifest = json.loads(MANIFEST.read_text())
    if manifest["fixtures"].get("toolcheck-delta.ts") != SOURCE_SHA:
        raise Review304Blocked("Synthetic toolcheck probe no longer pinned")
    tsc = shutil.which("tsc")
    node = shutil.which("node")
    if not tsc or not node:
        raise Review304Blocked("Local pinned compiler/runtime absent")
    tsver = subprocess.run(  # noqa: S603 - version introspection only
        [tsc, "--version"],
        text=True,
        capture_output=True,
        check=True,
        timeout=7,
    ).stdout.strip()
    if tsver != "Version 6.0.3":
        raise Review304Blocked("Unreviewed TypeScript compiler version")
    results = []
    with tempfile.TemporaryDirectory(prefix="mods304-firstparty-ts-") as root:
        tmp = Path(root)
        for version, (source, source_hash) in (("302", files["old"]), ("304", files["new"])):
            work = tmp / version
            work.mkdir(mode=0o700)
            (work / "claude-core.d.ts").write_bytes(source.read_bytes())
            (work / "reviewed-native-hook.ts").write_bytes(FIXTURE.read_bytes())
            config = {
                "compilerOptions": {
                    "target": "ES2023",
                    "module": "ESNext",
                    "moduleResolution": "Bundler",
                    "strict": True,
                    "noEmit": True,
                    "skipLibCheck": True,
                    "types": [],
                    "lib": ["ES2023"],
                },
                "include": ["claude-core.d.ts", "reviewed-native-hook.ts"],
            }
            (work / "tsconfig.json").write_text(json.dumps(config, sort_keys=True) + "\n")
            code, errors = _tsc(work, tsc, node)
            if version == "302":
                if code == 0 or sorted(errors) != ["TS2339", "TS2345"]:
                    raise Review304Blocked("302 unexpectedly accepts the 304-only API")
            elif code != 0 or errors:
                raise Review304Blocked("Native 304 types do not accept their own API")
            results.append(
                {
                    "target_cli": "2.1." + version,
                    "core_types_sha256": source_hash,
                    "typescript_exit_code": code,
                    "diagnostic_codes": sorted(errors),
                    "known_304_only_api_contract_accepted": version == "304",
                }
            )
    return {
        "schema_version": 1,
        "source": "binary-extracted official native Claude Code CLI302/304 core types",
        "typescript_version": tsver,
        "source_reviewed_prototype_sha256": SOURCE_SHA,
        "native_304_binary_sha256": NATIVE304,
        "official_304_release_asset_sha256": ASSET304,
        "reference_302_core_types_sha256": CORE302,
        "new_304_core_types_sha256": CORE304,
        "same_source_302_rejected_and_304_accepted": True,
        "two_typecheck_runs": results,
        "typecheck_no_emit": True,
        "native_type_source_content_exported_to_git": False,
        "model_generated_code_executed": False,
        "model_or_account_network_requests": 0,
        "live_user_permission_result_verified": False,
        "stable_release_authorized": False,
    }


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--core302", type=Path, required=True)
    p.add_argument("--core304", type=Path, required=True)
    p.add_argument("--binary304", type=Path, required=True)
    p.add_argument("--asset304", type=Path, required=True)
    p.add_argument("--out", type=Path, required=True)
    args = p.parse_args()
    if args.out.exists() or args.out.is_symlink():
        raise SystemExit("REFUSED: historical native type diff already saved")
    try:
        report = audit(args.core302, args.core304, args.binary304, args.asset304)
    except (Review304Blocked, ValueError, OSError, subprocess.SubprocessError):
        raise SystemExit("BLOCKED: official native CLI304 types not verified") from None
    args.out.write_text(json.dumps(report, sort_keys=True, indent=2) + "\n")
    print(
        {
            "same_source_cli302": "REJECT",
            "same_source_cli304": "TYPECHECK_PASS",
            "no_model_or_account_requests": 0,
            "stable_release_authorized": False,
        }
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
